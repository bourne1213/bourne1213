# -*- coding: utf-8 -*-
"""
板块映射：按股票名称关键词近似猜测所属板块。

说明：无精确行业数据源（Tushare 限频、东财被墙）时的兜底方案，
供 screener / report / app 共用，避免多处维护不同版本的关键词表。
"""
from __future__ import annotations

# 行业关键词近似（后续可换 Tushare/东财精确行业）
SECTOR_KEYWORDS = {
    "半导体": ["半导体", "芯片", "微电子", "存储", "兆易", "普冉", "中芯", "华虹", "澜起", "北方华创", "韦尔", "君正"],
    "光模块/通信": ["通信", "光", "天孚", "新易盛", "中际旭创", "华工", "烽火", "中天"],
    "白酒/消费": ["茅台", "五粮液", "泸州", "汾酒", "酒", "食品", "饮料", "消费"],
    "银行": ["银行"],
    "保险/券商": ["保险", "平安", "金融", "证券", "券商", "东财"],
    "新能源": ["新能源", "光伏", "风电", "锂", "宁德", "储能", "隆基", "阳光"],
    "医药": ["医药", "生物", "医疗", "药明", "恒瑞"],
    "军工": ["军工", "航发", "国防", "中航"],
    "计算机/软件": ["软件", "计算机", "信息", "科大讯飞", "用友"],
    "地产": ["地产", "万科", "保利", "招商蛇口"],
}


def guess_sector(name: str) -> str:
    """按名称关键词返回板块名，未命中返回「其他」。"""
    for sec, kws in SECTOR_KEYWORDS.items():
        for kw in kws:
            if kw in str(name):
                return sec
    return "其他"
